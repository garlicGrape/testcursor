import type { Problem } from "./types";

function sql(
  p: Omit<Problem, "kind" | "local" | "xp" | "track"> & { track?: Problem["track"]; xp?: number },
): Problem {
  return {
    kind: "sql",
    local: true,
    ...p,
    track: p.track ?? ["sql", "data-science"],
    xp: p.xp ?? (p.difficulty === "easy" ? 100 : p.difficulty === "hard" ? 350 : 200),
  };
}

