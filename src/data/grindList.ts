import type { Problem } from "./types";

function item(
  p: Omit<Problem, "local" | "track" | "kind" | "xp"> & { track?: Problem["track"]; xp?: number },
): Problem {
  return {
    kind: "python",
    local: false,
    ...p,
    track: p.track ?? ["core"],
    xp: p.xp ?? (p.difficulty === "easy" ? 100 : p.difficulty === "hard" ? 350 : 200),
  };
}

